CITE_ORDER: list[str] = []


def cite(m):
    keys = [k.strip() for k in m.group(1).split(",")]
    nums = []
    for k in keys:
        if k not in BIB:
            raise KeyError(k)
        if k not in CITE_ORDER:
            CITE_ORDER.append(k)
        nums.append(CITE_ORDER.index(k) + 1)
    return "[" + ", ".join(str(n) for n in sorted(nums)) + "]"


def resolve(text: str) -> str:
    return re.sub(r"\{([a-z, ]+)\}", cite, text)


