def FIGURE(path, caption, width=14.5):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.space_before = Pt(6)
    p.add_run().add_picture(str(path), width=Cm(width))
    caption = re.sub(r"^(Рисунок \d+) – ", r"\1. ", caption)
    c = P(caption, indent=False, align="c", spacing=1.0, after=14)
    return c


def set_cell_borders(table):
    tbl = table._tbl
    pr = tbl.tblPr
    b = OxmlElement("w:tblBorders")
    for e in ("top", "left", "bottom", "right", "insideH", "insideV"):
        x = OxmlElement(f"w:{e}")
        x.set(qn("w:val"), "single")
        x.set(qn("w:sz"), "4")
        x.set(qn("w:space"), "0")
        x.set(qn("w:color"), "000000")
        b.append(x)
    pr.append(b)


def TABLE(caption, header, rows, widths=None, size=12, bold_last=False):
    num, _, name = caption.partition(" – ")
    P(num + ".", indent=True, align="l", keep=True, spacing=1.0, after=0)
    P(name, indent=True, align="l", keep=True, spacing=1.0, after=4)
    t = doc.add_table(rows=1, cols=len(header))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    set_cell_borders(t)
    allrows = [header] + rows
    for ri, row in enumerate(allrows):
        cells = t.rows[0].cells if ri == 0 else t.add_row().cells
        for ci, val in enumerate(row):
            cell = cells[ci]
            cell.text = ""
            para = cell.paragraphs[0]
            para.paragraph_format.line_spacing = 1.0
            para.paragraph_format.first_line_indent = Cm(0)
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER if (ri == 0 or ci > 0) else WD_ALIGN_PARAGRAPH.LEFT
            run = para.add_run(resolve(str(val)))
            run.font.size = Pt(size)
            run.bold = ri == 0 or (bold_last and ri == len(allrows) - 1)
            if widths:
                cell.width = Cm(widths[ci])
    # шапка повторяется при переносе
    trPr = t.rows[0]._tr.get_or_add_trPr()
    th = OxmlElement("w:tblHeader")
    th.set(qn("w:val"), "true")
    trPr.append(th)
    for row in t.rows:
        trPr = row._tr.get_or_add_trPr()
        cs = OxmlElement("w:cantSplit")
        cs.set(qn("w:val"), "true")
        trPr.append(cs)
    sp = doc.add_paragraph()
    sp.paragraph_format.line_spacing = 1.0
    sp.paragraph_format.space_after = Pt(6)
    return t


