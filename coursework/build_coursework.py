def add_field(run, instr):
    for t, txt in (("begin", None), (None, instr), ("end", None)):
        if t:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), t)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = txt
        run._r.append(el)


HEADINGS: list[tuple[int, str]] = []


def P(text, indent=True, align="j", bold=False, italic=False, keep=False, size=None, spacing=None, after=None):
    p = doc.add_paragraph()
    p.alignment = {"j": WD_ALIGN_PARAGRAPH.JUSTIFY, "c": WD_ALIGN_PARAGRAPH.CENTER,
                   "l": WD_ALIGN_PARAGRAPH.LEFT, "r": WD_ALIGN_PARAGRAPH.RIGHT}[align]
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    if keep:
        p.paragraph_format.keep_with_next = True
    if spacing:
        p.paragraph_format.line_spacing = spacing
    if after is not None:
        p.paragraph_format.space_after = Pt(after)
    # **жирный** внутри текста
    for i, chunk in enumerate(re.split(r"\*\*(.+?)\*\*", resolve(text))):
        if not chunk:
            continue
        run = p.add_run(chunk)
        run.bold = bold or (i % 2 == 1)
        run.italic = italic
        if size:
            run.font.size = Pt(size)
    return p


def H1(text, new_page=True):
    if new_page:
        doc.add_page_break()
    h = doc.add_heading(text, level=1)
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER if text in ("ВВЕДЕНИЕ", "ЗАКЛЮЧЕНИЕ", "СПИСОК ИСПОЛЬЗОВАННОЙ ЛИТЕРАТУРЫ", "СОДЕРЖАНИЕ") else WD_ALIGN_PARAGRAPH.LEFT
    h.paragraph_format.first_line_indent = Cm(1.25) if h.alignment == WD_ALIGN_PARAGRAPH.LEFT else Cm(0)
    HEADINGS.append((1, text))
    return h


